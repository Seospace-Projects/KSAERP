/**
 * Bundle only app source for Vercel. Keep node_modules external so packages
 * that use require("path") / createRequire keep working (avoids
 * "Dynamic require of path is not supported" in ESM bundles).
 */
import * as esbuild from 'esbuild';
import { mkdirSync } from 'node:fs';

mkdirSync('api', { recursive: true });

await esbuild.build({
  entryPoints: ['src/server/vercelEntry.ts'],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outfile: 'api/handler.mjs',
  packages: 'external',
  logLevel: 'info',
  banner: {
    js: '/* Generated by scripts/build-api.mjs — do not edit by hand */',
  },
});

console.log('Wrote api/handler.mjs');
